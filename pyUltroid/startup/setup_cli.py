"""BoudyOS offline maintenance (no Telegram boot, network probes or pip execution).

Usage:
  python -m pyUltroid setup
  python -m pyUltroid doctor
  python -m pyUltroid help
"""
from __future__ import annotations

import getpass
import importlib.util
import os
import re
import shlex
import sys
from pathlib import Path
from types import SimpleNamespace

# Source paths never depend on a mutable runtime working directory.
ROOT = Path(__file__).resolve().parents[2]
ENV_PATH = Path.cwd() / ".env"
ENV_SAMPLE = ROOT / ".env.sample"
PROFILES = {
    "minimal": ["requirements.txt"],
    "db-redis": ["requirements.txt", "requirements/database.txt"],
    "db-mongo": ["requirements.txt", "requirements/database.txt"],
    "db-postgres": ["requirements.txt", "requirements/database.txt"],
    "full": ["requirements.txt", "requirements/database.txt", "requirements/media.txt"],
    "termux": ["requirements.txt"],
}


def _is_interactive():
    return sys.stdin.isatty() and sys.stdout.isatty()


def _prompt(message, default="", secret=False):
    prompt = f"{message}: " if secret else f"{message} [{default}]: "
    return (getpass.getpass(prompt) if secret else input(prompt)).strip() or default


def _write_env(values):
    lines = ["# Generated by python -m pyUltroid setup; keep private."]
    for key, value in values.items():
        value = str(value)
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", key) or any(char in value for char in "\r\n\x00"):
            raise ValueError("Invalid env key or multiline value; file was not written.")
        # Single quoted dotenv strings preserve spaces, comments and dollar signs.
        value = value.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"{key}='{value}'")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(ENV_PATH, flags, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        os.fchmod(stream.fileno(), 0o600)
        stream.write("\n".join(lines) + "\n")
    print("Created private .env; existing files are never overwritten.")


def install_command(profile, version=None):
    version = tuple(version or sys.version_info[:2])
    constraints = {(3, 10): "py310.txt", (3, 13): "py313.txt"}
    if version not in constraints:
        raise ValueError("Use supported Python 3.10 or 3.13 with matching constraints.")
    command = [sys.executable, "-m", "pip", "install", "-c", str(ROOT / "constraints" / constraints[version])]
    for requirement in PROFILES[profile]:
        path = ROOT / requirement
        if not path.is_file():
            raise ValueError("Required installation profile is unavailable.")
        command.extend(["-r", str(path)])
    return command


def _load_validator():
    spec = importlib.util.spec_from_file_location("_boudyos_validate", ROOT / "pyUltroid/startup/config_validate.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _doctor_values():
    # Optional dotenv parsing is local only. Never import pyUltroid.configs/startup.
    values = {}
    if ENV_PATH.is_symlink():
        raise ValueError("Refusing symlink .env.")
    if ENV_PATH.is_file():
        try:
            from dotenv import dotenv_values
        except ImportError:
            print("WARN: .env not read without python-dotenv; checking process environment only.")
        else:
            values.update(dotenv_values(ENV_PATH, interpolate=False))
    values.update(os.environ)
    keys = ("API_ID", "API_HASH", "SESSION", "BOT_TOKEN", "BOTMODE", "REDIS_URI",
            "REDISHOST", "REDISPORT", "MONGO_URI", "DATABASE_URL")
    result = {key: values.get(key) for key in keys}
    result["REDIS_URI"] = result["REDIS_URI"] or values.get("REDIS_URL")
    result["STRICT_CONFIG"] = values.get("ULTROID_STRICT_CONFIG")
    return SimpleNamespace(**result)


def cmd_doctor():
    print("BoudyOS doctor (offline; no database connections)")
    print(f"Python: {sys.version_info.major}.{sys.version_info.minor}")
    print("Dependencies (availability only; modules are not imported):")
    for module in ("telethonpatch", "telethon", "decouple", "dotenv", "redis", "pymongo", "psycopg2"):
        print(f"  {'OK' if importlib.util.find_spec(module) else '--'} {module}")
    try:
        errors, warnings = _load_validator().collect_config_issues(_doctor_values())
    except (OSError, ValueError):
        print("ERR: Unable to safely read local configuration.")
        return 1
    for issue in warnings:
        print("WARN: " + issue)
    for issue in errors:
        print("ERR: " + issue)
    return 1 if errors else 0


def _print_install(profile):
    try:
        print("Install outside the bot (not executed):\n  " + shlex.join(install_command(profile)))
    except ValueError as error:
        print(str(error))


def cmd_setup():
    print("BoudyOS setup — hosted platforms should set dashboard config vars instead.")
    if not _is_interactive():
        print("Non-interactive: create a private .env (chmod 600), using .env.sample as a guide; no files changed.")
        _print_install("minimal")
        return 0
    if ENV_PATH.exists() or ENV_PATH.is_symlink():
        print("Refusing existing .env; edit it manually. No files changed.")
        return 1
    values = {
        "API_ID": _prompt("API_ID from my.telegram.org"),
        "API_HASH": _prompt("API_HASH", secret=True),
        "SESSION": _prompt("SESSION (generate with bash sessiongen)", secret=True),
        "BOT_TOKEN": _prompt("BOT_TOKEN (optional)", secret=True),
        "LOG_CHANNEL": _prompt("LOG_CHANNEL (0 disables log delivery)", "0"),
    }
    backend = _prompt("Database: local / redis / mongo / postgres", "local").lower()
    profile = "minimal"
    if backend == "redis":
        values["REDIS_URI"] = _prompt("REDIS_URI host:port")
        values["REDIS_PASSWORD"] = _prompt("REDIS_PASSWORD", secret=True)
        profile = "db-redis"
    elif backend in {"mongo", "postgres"}:
        values["MONGO_URI" if backend == "mongo" else "DATABASE_URL"] = _prompt("Provider URI", secret=True)
        profile = "db-" + backend
    elif backend != "local":
        print("Unknown database; no files changed.")
        return 2
    for key in ("SKIP_AUTOBOT", "SKIP_AUTOPILOT", "SKIP_ASSISTANT_CUSTOMIZE"):
        values[key] = _prompt(key + " (true/false)", "true")
    values["ULTROID_STRICT_CONFIG"] = _prompt("Require remote database (true/false)", "false")
    errors, _ = _load_validator().collect_config_issues(SimpleNamespace(**values))
    if errors:
        for issue in errors:
            print("ERR: " + issue)
        return 1
    try:
        _write_env(values)
    except (OSError, ValueError):
        print("Could not securely create .env; existing files are never overwritten.")
        return 1
    _print_install(profile)
    print("Start with python -m pyUltroid; diagnose with python -m pyUltroid doctor.")
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in {"help", "-h", "--help"}:
        print(__doc__)
        return 0
    if len(argv) != 1:
        print("Expected one maintenance command; see python -m pyUltroid help.")
        return 2
    if argv[0] == "setup":
        return cmd_setup()
    if argv[0] == "doctor":
        return cmd_doctor()
    print("Unknown maintenance command; see python -m pyUltroid help.")
    return 2
